'use client';

// Ask: plain-language questions about accounts and promises, answered by a Cortex Agent that uses
// Cortex Analyst over the COLLECTIONS_SV semantic view.
import { Bot, Send } from 'lucide-react';
import { useState } from 'react';
import { AiMeta, AiPanel, Reasoning, Sources, StreamText } from '@/components/Reasoning';
import { ErrorBox, PageBand, PoweredBy } from '@/components/ui';
import { SAMPLE_QUESTIONS, ask } from '@/lib/client';
import type { AiText } from '@/lib/types';

const STEPS = ['Sending the question to COLLECTIONS_AGENT (Cortex Agents)', 'Planning with the COLLECTIONS_SV semantic view',
  'Generating SQL with Cortex Analyst and running it on the warehouse', 'Writing the answer from the query results'];

export default function AskPage() {
  const [q, setQ] = useState('');
  const [turns, setTurns] = useState<{ q: string; a?: AiText; error?: string }[]>([]);
  const busy = turns.length > 0 && !turns[turns.length - 1].a && !turns[turns.length - 1].error;
  const go = (question: string) => {
    if (!question.trim() || busy) return;
    setQ('');
    setTurns((t) => [...t, { q: question }]);
    ask(question).then((a) => setTurns((t) => t.map((x, i) => (i === t.length - 1 ? { ...x, a } : x))),
      (e) => setTurns((t) => t.map((x, i) => (i === t.length - 1 ? { ...x, error: String(e.message ?? e) } : x))));
  };
  return (
    <div className="space-y-5">
      <PageBand eyebrow="Ask the desk" title="Questions about accounts and promises"
        sub="A Cortex Agent answers from the collections semantic view and shows the SQL it ran."
        chips={<><PoweredBy onBand>Cortex Agents</PoweredBy><PoweredBy onBand>Cortex Analyst · semantic view</PoweredBy></>} />
      <div className="relative z-10 max-w-3xl mx-auto space-y-4">
        <div className="panel p-4">
          <div className="text-[11px] uppercase tracking-[.08em] font-bold muted mb-2">Try one</div>
          <div className="flex flex-wrap gap-2">{SAMPLE_QUESTIONS.map((s) => <button key={s} className="btn !text-xs" disabled={busy} onClick={() => go(s)}>{s}</button>)}</div>
        </div>
        {turns.map((t, i) => (
          <div key={i} className="space-y-2 rise">
            <div className="ml-auto max-w-[85%] w-fit rounded-2xl rounded-br-md px-4 py-2.5 text-sm" style={{ background: 'var(--dusk)', color: 'var(--on-dusk)' }}>{t.q}</div>
            {t.error ? <ErrorBox error={t.error} /> : (
              <AiPanel title="Answer" icon={<Bot className="w-4 h-4" style={{ color: 'var(--dusk)' }} aria-hidden />} right={t.a && <AiMeta ai={t.a} />}>
                {!t.a ? <Reasoning kind="ask" steps={STEPS} /> : (
                  <>
                    <StreamText text={t.a.text} />
                    {t.a.sql && <details className="mt-3"><summary className="text-xs muted cursor-pointer">SQL generated by Cortex Analyst</summary>
                      <pre className="mono text-[11px] rounded-lg p-3 mt-2 overflow-x-auto" style={{ background: 'var(--surface-2)' }}>{t.a.sql}</pre></details>}
                    <Sources items={[{ label: 'COLLECTIONS_SV semantic view' }, { label: t.a.source === 'sample' ? 'Captured live agent answer' : 'Query run just now' }]} />
                  </>
                )}
              </AiPanel>
            )}
          </div>
        ))}
        <form className="panel p-2 flex gap-2 sticky bottom-3" onSubmit={(e) => { e.preventDefault(); go(q); }}>
          <input className="field !border-0" value={q} onChange={(e) => setQ(e.target.value)} placeholder="Ask about delinquency, promises, offers or contact channels" aria-label="Question" />
          <button className="btn btn-ai" disabled={busy} type="submit" aria-label="Ask"><Send className="w-4 h-4" aria-hidden /></button>
        </form>
        <p className="text-xs muted">The agent only reads the collections semantic view. Answers describe this synthetic data set; check the numbers before acting.</p>
      </div>
    </div>
  );
}
